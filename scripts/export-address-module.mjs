#!/usr/bin/env node
/**
 * scripts/export-address-module.mjs
 *
 * Bundles the canonical knowledge-unit address grammar from
 * `@cognnitive/nn-core` (`console/unit-address.ts`) into a standalone IIFE:
 * `iNNfo/specs/bluepriNNts/console/innfo-address.generated.js` (window.InnfoAddress).
 *
 * The console runtime consumes `window.InnfoAddress` so badge addresses are built and
 * parsed by the SAME implementation as the engine (single source of truth).
 */

import { join, dirname, resolve } from 'node:path'
import { fileURLToPath } from 'node:url'
import { readFileSync, writeFileSync, existsSync } from 'node:fs'
import { build } from 'esbuild'

const here = dirname(fileURLToPath(import.meta.url))
const repoRoot = join(here, '..')
const entryPoint = join(repoRoot, 'iNNfo', 'packages', 'nn-core', 'src', 'console', 'unit-address.ts')
const defaultOutfile = join(repoRoot, 'iNNfo', 'specs', 'bluepriNNts', 'console', 'innfo-address.generated.js')

const args = process.argv.slice(2)
const isCheck = args.includes('--check')
const outIndex = args.indexOf('--out')
const targetOutfile = outIndex !== -1 && args[outIndex + 1] ? resolve(process.cwd(), args[outIndex + 1]) : defaultOutfile

async function run() {
  const result = await build({
    entryPoints: [entryPoint],
    bundle: true,
    platform: 'browser',
    format: 'iife',
    globalName: 'InnfoAddress',
    target: 'es2020',
    absWorkingDir: repoRoot,
    preserveSymlinks: true,
    write: false,
    banner: {
      js: '/*! innfo-address.generated.js — Generated by scripts/export-address-module.mjs — DO NOT EDIT */',
    },
    footer: {
      js: 'if (typeof module === "object" && module.exports) module.exports = InnfoAddress;\nif (typeof globalThis !== "undefined") globalThis.InnfoAddress = InnfoAddress;',
    },
    metafile: true,
  })

  const generatedCode = result.outputFiles[0].text.replace(/(?:\.\.\/)+node_modules\//g, 'node_modules/')

  if (isCheck) {
    if (!existsSync(targetOutfile)) {
      console.error(`[export-address-module] Drift: ${targetOutfile} does not exist.`)
      process.exit(1)
    }
    if (readFileSync(targetOutfile, 'utf8') !== generatedCode) {
      console.error(`[export-address-module] Drift: ${targetOutfile} is out of date. Run "node scripts/export-address-module.mjs".`)
      process.exit(1)
    }
    console.log(`[export-address-module] OK: ${targetOutfile} matches generated bundle.`)
    return
  }

  writeFileSync(targetOutfile, generatedCode, 'utf8')
  console.log(`wrote ${targetOutfile} (${Buffer.byteLength(generatedCode, 'utf8')} bytes)`)
}

run().catch((err) => {
  console.error(err)
  process.exit(1)
})
