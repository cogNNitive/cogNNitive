#!/usr/bin/env node
/**
 * scripts/build-console-payload.mjs
 *
 * Bundles the console payload builder and feedback ledger engine from
 * `@cognnitive/innfo-core` into a standalone CommonJS bundle:
 * `iNNfo/specs/bluepriNNts/console/console-payload.generated.cjs`
 *
 * This enables exporter scripts and compile procedures to use the single canonical
 * payload builder without ESM/TS runtime friction.
 */

import { join, dirname } from 'node:path'
import { fileURLToPath } from 'node:url'
import { build } from 'esbuild'

const here = dirname(fileURLToPath(import.meta.url))
const repoRoot = join(here, '..')
const entryPoint = join(repoRoot, 'iNNfo', 'packages', 'innfo-core', 'src', 'console', 'index.ts')
const outfile = join(repoRoot, 'iNNfo', 'specs', 'bluepriNNts', 'console', 'console-payload.generated.cjs')

async function run() {
  const result = await build({
    entryPoints: [entryPoint],
    bundle: true,
    platform: 'node',
    format: 'cjs',
    target: 'node20',
    outfile,
    banner: {
      js: '/*! console-payload.generated.cjs — Generated by scripts/build-console-payload.mjs — DO NOT EDIT */',
    },
  })

  console.log(`wrote ${outfile}`)
}

run().catch((err) => {
  console.error(err)
  process.exit(1)
})
