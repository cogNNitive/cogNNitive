#!/usr/bin/env node
/**
 * scripts/build-console-payload.mjs
 *
 * Bundles the console payload builder and feedback ledger engine from
 * `@cognnitive/nn-core` into a standalone CommonJS bundle:
 * `iNNfo/specs/bluepriNNts/console/console-payload.generated.cjs`
 *
 * Also bundles the core slug primitives into an IIFE bundle:
 * `iNNfo/specs/bluepriNNts/console/innfo-slug.generated.js` (InnfoSlug)
 *
 * This enables exporter scripts and compile procedures to use the single canonical
 * payload builder and slug primitives without ESM/TS runtime friction.
 */

import { join, dirname, resolve } from 'node:path'
import { fileURLToPath } from 'node:url'
import { readFileSync, writeFileSync, existsSync } from 'node:fs'
import { build } from 'esbuild'

const here = dirname(fileURLToPath(import.meta.url))
const repoRoot = join(here, '..')
const entryPoint = join(repoRoot, 'iNNfo', 'packages', 'nn-core', 'src', 'console', 'index.ts')
const defaultOutfile = join(repoRoot, 'iNNfo', 'specs', 'bluepriNNts', 'console', 'console-payload.generated.cjs')

const slugEntryPoint = join(repoRoot, 'iNNfo', 'packages', 'nn-core', 'src', 'parser', 'slug.ts')
const defaultSlugOutfile = join(repoRoot, 'iNNfo', 'specs', 'bluepriNNts', 'console', 'innfo-slug.generated.js')

// The exporter CJS ships a stub registry instead of the ~500 KB canonical one: only the `changes`
// version (read from its blueprint) is kept; every other blueprint must resolve from disk, else the
// console falls back to the derived schema. The MCP and core keep the full registry.
const changesSpecPath = join(repoRoot, 'iNNfo', 'specs', 'bluepriNNts', 'changes', 'spec_NN.md')
const changesBlueprintVersion = /^blueprint_version:\s*"?([^"\r\n]+)"?/m.exec(readFileSync(changesSpecPath, 'utf8'))?.[1]
if (!changesBlueprintVersion) throw new Error(`blueprint_version not found in ${changesSpecPath}`)

const offlineRegistryStub = {
  name: 'offline-registry-stub',
  setup(b) {
    b.onResolve({ filter: /canonical-registry/ }, () => ({ path: 'canonical-registry-stub', namespace: 'stub' }))
    b.onLoad({ filter: /.*/, namespace: 'stub' }, () => ({
      loader: 'js',
      contents: `export const CANONICAL_BLUEPRINTS = {}
export function findCanonicalBlueprint(key) {
  return key === 'changes' ? { name: 'changes', version: ${JSON.stringify(changesBlueprintVersion)}, aliases: [], specContent: '' } : null
}`,
    }))
  },
}

const args = process.argv.slice(2)
const isCheck = args.includes('--check')
const outIndex = args.indexOf('--out')
const targetOutfile = outIndex !== -1 && args[outIndex + 1] ? resolve(process.cwd(), args[outIndex + 1]) : defaultOutfile
const slugOutIndex = args.indexOf('--slug-out')
const targetSlugOutfile = slugOutIndex !== -1 && args[slugOutIndex + 1] ? resolve(process.cwd(), args[slugOutIndex + 1]) : defaultSlugOutfile

async function run() {
  const result = await build({
    entryPoints: [entryPoint],
    bundle: true,
    platform: 'node',
    format: 'cjs',
    target: 'node20',
    absWorkingDir: repoRoot,
    // Session worktrees junction node_modules to the primary checkout; without
    // this, esbuild embeds the junction's real path and the mirror drifts.
    preserveSymlinks: true,
    write: false,
    plugins: [offlineRegistryStub],
    banner: {
      js: '/*! console-payload.generated.cjs — Generated by scripts/build-console-payload.mjs — DO NOT EDIT */',
    },
    metafile: true,
  })

  const generatedCode = result.outputFiles[0].text

  const slugResult = await build({
    entryPoints: [slugEntryPoint],
    bundle: true,
    platform: 'browser',
    format: 'iife',
    globalName: 'InnfoSlug',
    target: 'es2020',
    absWorkingDir: repoRoot,
    write: false,
    banner: {
      js: '/*! innfo-slug.generated.js — Generated by scripts/build-console-payload.mjs — DO NOT EDIT */',
    },
    footer: {
      js: 'if (typeof module === "object" && module.exports) module.exports = InnfoSlug;\nif (typeof globalThis !== "undefined") globalThis.InnfoSlug = InnfoSlug;',
    },
    metafile: true,
  })

  const rawSlugCode = slugResult.outputFiles[0].text
  const generatedSlugCode = rawSlugCode.replace(/(?:\.\.\/)+node_modules\//g, 'node_modules/')

  if (isCheck) {
    let hasError = false
    if (!existsSync(targetOutfile)) {
      console.error(`[build-console-payload] Drift detected: mirror file ${targetOutfile} does not exist.`)
      hasError = true
    } else {
      const existingCode = readFileSync(targetOutfile, 'utf8')
      if (existingCode !== generatedCode) {
        console.error(`[build-console-payload] Drift detected: mirror file ${targetOutfile} is out of date.`)
        hasError = true
      }
    }

    if (slugOutIndex !== -1 || outIndex === -1) {
      if (!existsSync(targetSlugOutfile)) {
        console.error(`[build-console-payload] Drift detected: mirror file ${targetSlugOutfile} does not exist.`)
        hasError = true
      } else {
        const existingSlugCode = readFileSync(targetSlugOutfile, 'utf8')
        if (existingSlugCode !== generatedSlugCode) {
          console.error(`[build-console-payload] Drift detected: mirror file ${targetSlugOutfile} is out of date.`)
          hasError = true
        }
      }
    }

    if (hasError) {
      console.error(`Run "node scripts/build-console-payload.mjs" to regenerate.`)
      process.exit(1)
    }

    console.log(`[build-console-payload] OK: ${targetOutfile} matches generated bundle.`)
    return
  }

  writeFileSync(targetOutfile, generatedCode, 'utf8')
  console.log(`wrote ${targetOutfile} (${Buffer.byteLength(generatedCode, 'utf8')} bytes)`)
  if (slugOutIndex !== -1 || outIndex === -1) {
    writeFileSync(targetSlugOutfile, generatedSlugCode, 'utf8')
    console.log(`wrote ${targetSlugOutfile} (${Buffer.byteLength(generatedSlugCode, 'utf8')} bytes)`)
  }
}

run().catch((err) => {
  console.error(err)
  process.exit(1)
})
