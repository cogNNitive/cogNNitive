#!/usr/bin/env node
/**
 * scripts/export-procedure-fold.mjs
 *
 * Bundles nn-core's pure `foldRun` implementation and its graph dependencies into a
 * standalone IIFE browser module:
 * `iNNfo/specs/bluepriNNts/console/nn-procedure-fold.generated.js` (window.nnProcedureFold).
 *
 * Included canonically in `nn-console.bundle.js` so the console runtime has access to
 * `foldRun` offline and without dynamic script injection or eval.
 */

import { join, dirname, resolve } from 'node:path'
import { fileURLToPath } from 'node:url'
import { readFileSync, writeFileSync, existsSync } from 'node:fs'
import { build } from 'esbuild'

const here = dirname(fileURLToPath(import.meta.url))
const repoRoot = join(here, '..')
const entryPoint = join(repoRoot, 'iNNfo', 'packages', 'nn-core', 'src', 'procedure', 'fold.ts')
const defaultOutfile = join(
  repoRoot,
  'iNNfo',
  'specs',
  'bluepriNNts',
  'console',
  'nn-procedure-fold.generated.js',
)

const args = process.argv.slice(2)
const isCheck = args.includes('--check')
const outIndex = args.indexOf('--out')
const targetOutfile =
  outIndex !== -1 && args[outIndex + 1]
    ? resolve(process.cwd(), args[outIndex + 1])
    : defaultOutfile

async function run() {
  const result = await build({
    entryPoints: [entryPoint],
    bundle: true,
    platform: 'browser',
    format: 'iife',
    globalName: 'nnProcedureFold',
    target: 'es2020',
    absWorkingDir: repoRoot,
    preserveSymlinks: true,
    write: false,
    banner: {
      js: '/*! nn-procedure-fold.generated.js — Generated by scripts/export-procedure-fold.mjs — DO NOT EDIT */',
    },
    footer: {
      js: [
        'if (typeof module === "object" && module.exports) module.exports = nnProcedureFold;',
        'if (typeof globalThis !== "undefined") { globalThis.nnProcedureFold = nnProcedureFold; globalThis.__nnFoldModule = nnProcedureFold; }',
        'if (typeof window !== "undefined") { window.nnProcedureFold = nnProcedureFold; window.__nnFoldModule = nnProcedureFold; }',
      ].join('\n'),
    },
    metafile: true,
  })

  let generatedCode = result.outputFiles[0].text.replace(
    /(?:\.\.\/)+node_modules\//g,
    'node_modules/',
  )

  try {
    const prettier = await import('prettier')
    const config = (await prettier.resolveConfig(targetOutfile)) || {}
    generatedCode = await prettier.format(generatedCode, {
      ...config,
      filepath: targetOutfile,
    })
  } catch {
    // Keep unformatted if prettier fails to load
  }

  if (isCheck) {
    if (!existsSync(targetOutfile)) {
      console.error(`[export-procedure-fold] Drift: ${targetOutfile} does not exist.`)
      process.exit(1)
    }
    if (readFileSync(targetOutfile, 'utf8') !== generatedCode) {
      console.error(
        `[export-procedure-fold] Drift: ${targetOutfile} is out of date. Run "node scripts/export-procedure-fold.mjs".`,
      )
      process.exit(1)
    }
    console.log(`[export-procedure-fold] OK: ${targetOutfile} matches generated bundle.`)
    return
  }

  writeFileSync(targetOutfile, generatedCode, 'utf8')
  console.log(`wrote ${targetOutfile} (${(generatedCode.length / 1024).toFixed(1)} KB)`)
}

run().catch((err) => {
  console.error(err)
  process.exit(1)
})
